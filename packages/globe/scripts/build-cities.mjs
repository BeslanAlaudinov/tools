// Builds src/data/cities.ts: every populated place of Natural Earth 1:10m with its Russian name,
// largest first, as one compact string ("name|lat|lon|ISO" per line). Public domain data.
//
//   curl -L -o places.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_10m_populated_places.geojson
//   node packages/globe/scripts/build-cities.mjs places.geojson
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
  console.error('usage: node build-cities.mjs <ne_10m_populated_places.geojson>');
  process.exit(1);
}
const places = JSON.parse(readFileSync(src, 'utf8')).features.map(f => f.properties);

// names Natural Earth has not caught up with
const RENAMES = { 'Нур-Султан': 'Астана', 'Алма-Ата': 'Алматы' };

const seen = new Set();
const rows = places
  .map(p => ({
    // the "|" and line breaks are the format's separators; Natural Earth names never contain them, but be safe
    name: String(p.NAME_RU || p.NAME)
      .replace(/[|\n]/g, ' ')
      .trim(),
    lat: Math.round(p.LATITUDE * 100) / 100,
    lon: Math.round(p.LONGITUDE * 100) / 100,
    iso: /^[A-Z]{2}$/.test(p.ISO_A2) ? p.ISO_A2 : '',
    pop: p.POP_MAX || 0,
  }))
  .map(r => ({ ...r, name: RENAMES[r.name] ?? r.name }))
  .filter(r => r.name && Number.isFinite(r.lat) && Number.isFinite(r.lon))
  .sort((a, b) => b.pop - a.pop)
  // the same name in the same country twice is one city recorded twice; keep the larger record
  .filter(r => {
    const key = `${r.name}|${r.iso}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });

const body = rows.map(r => `${r.name}|${r.lat}|${r.lon}|${r.iso}`).join('\n');
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'cities.ts');
writeFileSync(
  out,
  `// Generated by scripts/build-cities.mjs from Natural Earth 1:10m populated places (public domain). Do not edit.\n` +
    `// One city per line, largest first: name|lat|lon|ISO 3166-1 alpha-2 (may be empty).\n` +
    `export const CITY_DATA = ${JSON.stringify(body)};\n`,
);
console.log(`${rows.length} cities → ${out} (${(Buffer.byteLength(body) / 1024).toFixed(0)} KB)`);
