// Builds data/countries.js: an equirectangular grid of country indices plus Russian names.
// Source: Natural Earth 1:50m admin-0 via world-atlas; names via i18n-iso-countries.
//
//   npm i world-atlas@2.0.2 topojson-client@3.1.0 i18n-iso-countries@7.11.0   (in any temp folder)
//   node packages/globe/scripts/build-countries.mjs <that-folder>/node_modules
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rasterize, ringsOf, encodeRuns } from './raster.mjs';

const modules = process.argv[2];
if (!modules) {
  console.error('usage: node build-countries.mjs <node_modules dir>');
  process.exit(1);
}
const require = createRequire(join(modules, 'noop.js'));
const topojson = require('topojson-client');
const iso = require('i18n-iso-countries');
iso.registerLocale(require('i18n-iso-countries/langs/ru.json'));
const topo = JSON.parse(readFileSync(join(modules, 'world-atlas', 'countries-50m.json'), 'utf8'));
const features = topojson.feature(topo, topo.objects.countries).features;

// features without an ISO code in Natural Earth
const EXTRA_RU = {
  Somaliland: 'Сомалиленд',
  Kosovo: 'Косово',
  'N. Cyprus': 'Северный Кипр',
  'Indian Ocean Ter.': 'Территории в Индийском океане',
  'Siachen Glacier': 'Ледник Сиачен',
};
// shorter everyday names where the ISO name is long
const SHORT_RU = {
  US: 'США',
  GB: 'Великобритания',
  AE: 'ОАЭ',
  KP: 'КНДР',
  KR: 'Южная Корея',
  CD: 'ДР Конго',
  CF: 'ЦАР',
  BA: 'Босния и Герцеговина',
  VA: 'Ватикан',
  MK: 'Северная Македония',
  MD: 'Молдова',
  IR: 'Иран',
  SY: 'Сирия',
  LA: 'Лаос',
  VN: 'Вьетнам',
  TZ: 'Танзания',
  BO: 'Боливия',
  VE: 'Венесуэла',
  RU: 'Россия',
  FM: 'Микронезия',
  CN: 'Китай',
  SH: 'Остров Святой Елены',
  TF: 'Французские Южные территории',
};

const W = 720,
  H = 360;
// several features can share one ISO code (e.g. Ashmore and Cartier Is. → AU): merge them
const byKey = new Map();
for (const f of features) {
  const a2 = f.id ? iso.numericToAlpha2(f.id) : null;
  const name = (a2 && (SHORT_RU[a2] || iso.getName(a2, 'ru'))) || EXTRA_RU[f.properties.name] || f.properties.name;
  const key = a2 || name;
  if (!byKey.has(key)) byKey.set(key, { name, code: a2 || '', rings: [] });
  byKey.get(key).rings.push(...ringsOf(f.geometry));
}
const entries = [...byKey.values()].sort((a, b) => a.name.localeCompare(b.name, 'ru'));

const grid = new Uint8Array(W * H);
const scratch = new Uint8Array(W * H);
entries.forEach((e, i) => {
  scratch.fill(0);
  rasterize(e.rings, W, H, scratch);
  for (let p = 0; p < W * H; p++) if (scratch[p]) grid[p] = i + 1;
});
// grow countries two cells into the sea so coastal dots of the finer land mask still find their country
for (let pass = 0; pass < 2; pass++) {
  const prev = grid.slice();
  for (let r = 0; r < H; r++)
    for (let c = 0; c < W; c++) {
      const p = r * W + c;
      if (prev[p]) continue;
      const n =
        prev[r * W + ((c + 1) % W)] ||
        prev[r * W + ((c + W - 1) % W)] ||
        (r > 0 && prev[p - W]) ||
        (r < H - 1 && prev[p + W]);
      if (n) grid[p] = n;
    }
}
const b64 = encodeRuns(grid, W, H, false);
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'countries.ts');
mkdirSync(dirname(out), { recursive: true });
const names = entries.map(e => [e.name, e.code]);
writeFileSync(
  out,
  `// Country index grid ${W}x${H}, equirectangular, RLE (value, run); index i+1 ↔ names[i]. Natural Earth 1:50m admin-0 (public domain).\n// Generated by scripts/build-countries.mjs — do not edit by hand.\nimport type { ValueMaskData } from '../geo';\n\nexport const COUNTRY_MASK: ValueMaskData = {\n  w: ${W},\n  h: ${H},\n  names: ${JSON.stringify(names)},\n  rle: '${b64}',\n};\n`,
);
console.log(`${entries.length} countries · ${b64.length} chars → ${out}`);
