// Builds data/land-mask.js: an equirectangular land/water bitmap, run-length encoded.
// Source: Natural Earth 1:50m land via the world-atlas npm package.
//
//   npm i world-atlas@2.0.2 topojson-client@3.1.0   (in any temp folder)
//   node packages/globe/scripts/build-land-mask.mjs <that-folder>/node_modules
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rasterize, ringsOf, encodeRuns } from './raster.mjs';

const modules = process.argv[2];
if (!modules) {
  console.error('usage: node build-land-mask.mjs <node_modules dir>');
  process.exit(1);
}
const require = createRequire(join(modules, 'noop.js'));
const topojson = require('topojson-client');
const topo = JSON.parse(readFileSync(join(modules, 'world-atlas', 'land-50m.json'), 'utf8'));
const land = topojson.feature(topo, topo.objects.land);

const W = 1440,
  H = 720;
const bits = rasterize(
  (land.features ?? [land]).flatMap(f => ringsOf(f.geometry)),
  W,
  H,
);
const landCount = bits.reduce((s, v) => s + v, 0);
const b64 = encodeRuns(bits, W, H, true);
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'land-mask.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Land mask ${W}x${H}, equirectangular, RLE (alternating runs, water first). Natural Earth 1:50m land (public domain).\n// Generated by scripts/build-land-mask.mjs — do not edit by hand.\nimport type { BinaryMaskData } from '../geo';\n\nexport const LAND_MASK: BinaryMaskData = { w: ${W}, h: ${H}, rle: '${b64}' };\n`,
);
console.log(`land ${((100 * landCount) / (W * H)).toFixed(1)}% · ${b64.length} chars → ${out}`);
